#!/usr/bin/env python3
"""Render a static SVG from a live SecuBrain PTY capture, not a mock-up.

Usage: python docs/render_terminal_preview.py dist/dashboard-pty-capture.ansi
Source capture is generated by docs/pty_smoke.py. No fonts, images, or
third-party graphics packages are required.
"""
from html import escape
from pathlib import Path
import re
import sys

input_file = Path(sys.argv[1] if len(sys.argv)>1 else "dist/dashboard-pty-capture.ansi")
output_file = Path(sys.argv[2] if len(sys.argv)>2 else "docs/assets/terminal-dashboard-v04.svg")
raw = input_file.read_bytes().decode("utf-8", errors="replace")
frames = raw.split("\x1b[H\x1b[0J")
frame = next((x for x in frames[1:] if "NEURAL LINK READY" in x and "─ WORKSPACE" in x and "COMMAND" in x), None)
if not frame:
    raise SystemExit("No terminal frame with a neural visualization was found")
frame = re.sub(r"\x1b\[[0-9;?]*[A-Za-z]", "", frame)
rows = [x.rstrip("\r") for x in frame.splitlines()][:38]
if not rows or "SECUBRAIN" not in "\n".join(rows):
    raise SystemExit("Unexpected live capture content")
width, height = 1340, 935
nodes = [f'<svg xmlns="http://www.w3.org/2000/svg" width="{width}" height="{height}" viewBox="0 0 {width} {height}">',
         '<rect width="100%" height="100%" rx="22" fill="#090F1B"/>',
         '<rect x="23" y="23" width="1294" height="890" rx="16" fill="#0C1423" stroke="#2A3C55" stroke-width="2"/>',
         '<rect x="23" y="23" width="1294" height="48" rx="16" fill="#162239"/>',
         '<circle cx="60" cy="47" r="7" fill="#E77688"/><circle cx="85" cy="47" r="7" fill="#F4CD78"/><circle cx="110" cy="47" r="7" fill="#79DAAD"/>',
         '<text x="670" y="54" text-anchor="middle" font-family="Arial, sans-serif" font-size="15" letter-spacing="3" fill="#AFBFD6">SECUBRAIN / LIVE TERMINAL SESSION</text>',
         '<g font-family="Cascadia Code, Consolas, DejaVu Sans Mono, monospace" font-size="16.5" xml:space="preserve">']
for n, line in enumerate(rows):
    color = "#A4C5D9"
    if "╭" in line or "╰" in line or "─" in line and "WORKSPACE" not in line and "ACTIVITY" not in line:
        color = "#5A99BC"
    if "●" in line or "◉" in line or "◆" in line:
        color = "#71E1D3"
    if "SECUBRAIN" in line: color = "#DCF8F5"
    if "WORKSPACE" in line or "ACTIVITY" in line or "COMMAND" in line: color = "#73AFCB"
    if "Engine ready" in line: color = "#8DECC4"
    nodes.append(f'<text x="56" y="{104+n*20}" fill="{color}">{escape(line)}</text>')
nodes.extend(['</g>','</svg>'])
output_file.parent.mkdir(parents=True,exist_ok=True)
output_file.write_text("\n".join(nodes), encoding="utf-8")
print(f"Wrote {output_file} from {len(rows)} rows of a live PTY session")
